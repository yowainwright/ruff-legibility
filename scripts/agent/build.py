#!/usr/bin/env python3
from __future__ import annotations

import argparse
import os
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from itertools import chain
from pathlib import Path
from typing import Literal, cast

AgentBuildTarget = Literal["package", "agents", "codex", "claude"]
RuleTarget = Literal["Claude", "Codex"]

SKILL_NAME = "ruff-legibility"
DEFAULT_BUILD_TARGET: AgentBuildTarget = "package"
BUILD_TARGETS: tuple[AgentBuildTarget, ...] = ("package", "agents", "codex", "claude")
REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
TEMPLATE_ROOT = Path(__file__).with_name("templates") / SKILL_NAME


@dataclass(frozen=True)
class AgentArtifact:
    target: AgentBuildTarget
    relative_path: Path
    content: str


def parse_build_targets(args: Sequence[str], env: Mapping[str, str]) -> tuple[AgentBuildTarget, ...]:
    target_value = _target_argument(args) or DEFAULT_BUILD_TARGET
    return _parse_target_value(target_value, env)


def detect_build_target(env: Mapping[str, str]) -> AgentBuildTarget | None:
    if env.get("CODEX_HOME"):
        return "codex"

    if env.get("CLAUDECODE") or env.get("CLAUDE_CODE"):
        return "claude"

    return None


def render_agent_rule_pointer(target: RuleTarget) -> str:
    shared_skill = "`.agents/skills/ruff-legibility/SKILL.md`"
    generate_command = "`uv run python -m scripts.agent.build --target agents`"
    lines = (
        f"# Ruff Legibility {target} Rules",
        f"Use {shared_skill} as the shared agent skill workflow.",
        f"Generate the shared skill with {generate_command} when it is missing.",
        "Keep this file generated by `scripts/agent/build.py`.",
    )
    return "\n\n".join(lines) + "\n"


def create_agent_artifacts(
    target: AgentBuildTarget,
    *,
    template_root: Path = TEMPLATE_ROOT,
) -> tuple[AgentArtifact, ...]:
    parsed_target = _parse_build_target(target)
    if parsed_target in {"package", "agents"}:
        destination_root = _skill_destination(parsed_target)
        return _create_skill_artifacts(parsed_target, destination_root, template_root)

    rule_target = _rule_target(parsed_target)
    relative_path = _rule_destination(parsed_target)
    content = render_agent_rule_pointer(rule_target)
    return (AgentArtifact(parsed_target, relative_path, content),)


def write_agent_artifacts(
    *,
    root: Path = REPOSITORY_ROOT,
    targets: Sequence[AgentBuildTarget] = (DEFAULT_BUILD_TARGET,),
) -> tuple[AgentArtifact, ...]:
    artifacts = _artifacts_for_targets(targets)
    for artifact in artifacts:
        destination = root / artifact.relative_path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(artifact.content, encoding="utf-8")
    return artifacts


def check_agent_artifacts(
    *,
    root: Path = REPOSITORY_ROOT,
    targets: Sequence[AgentBuildTarget] = (DEFAULT_BUILD_TARGET,),
) -> tuple[Path, ...]:
    artifacts = _artifacts_for_targets(targets)
    stale_paths = (artifact.relative_path for artifact in artifacts if _is_stale(root, artifact))
    return tuple(stale_paths)


def main(args: Sequence[str] | None = None, env: Mapping[str, str] | None = None) -> int:
    command_args = _command_args(args)
    command_env = env if env is not None else os.environ
    parser = _build_parser()
    options = parser.parse_args(command_args)

    try:
        targets = _parse_target_value(options.target, command_env)
    except ValueError as error:
        parser.error(str(error))

    root = Path(options.root).resolve()
    if options.check:
        return _check_command(root, targets)
    return _write_command(root, targets)


def _command_args(args: Sequence[str] | None) -> tuple[str, ...]:
    if args is not None:
        return tuple(args)
    return tuple(sys.argv[1:])


def _parse_target_value(value: str, env: Mapping[str, str]) -> tuple[AgentBuildTarget, ...]:
    if value == "all":
        return BUILD_TARGETS

    if value == "auto":
        detected_target = detect_build_target(env)
        return (detected_target or DEFAULT_BUILD_TARGET,)

    parsed_targets = (_parse_build_target(item.strip()) for item in value.split(","))
    return tuple(dict.fromkeys(parsed_targets))


def _parse_build_target(value: str) -> AgentBuildTarget:
    if value not in BUILD_TARGETS:
        raise ValueError(f"unknown agent build target: {value}")
    return cast(AgentBuildTarget, value)


def _target_argument(args: Sequence[str]) -> str | None:
    target_prefix = "--target="
    equals_arguments = (argument for argument in args if argument.startswith(target_prefix))
    equals_argument = next(equals_arguments, None)
    if equals_argument:
        return equals_argument.removeprefix(target_prefix)

    try:
        target_index = args.index("--target")
        target_value = args[target_index + 1]
    except (ValueError, IndexError):
        return None

    if target_value.startswith("--"):
        return None
    return target_value


def _skill_destination(target: AgentBuildTarget) -> Path:
    if target == "package":
        return Path("src", "ruff_legibility", "skills", SKILL_NAME)
    return Path(".agents", "skills", SKILL_NAME)


def _rule_target(target: AgentBuildTarget) -> RuleTarget:
    if target == "codex":
        return "Codex"
    return "Claude"


def _rule_destination(target: AgentBuildTarget) -> Path:
    if target == "codex":
        return Path(".codex", "rules", f"{SKILL_NAME}.md")
    return Path(".claude", "rules", f"{SKILL_NAME}.md")


def _create_skill_artifacts(
    target: AgentBuildTarget,
    destination_root: Path,
    template_root: Path,
) -> tuple[AgentArtifact, ...]:
    candidate_paths = template_root.rglob("*")
    template_paths = sorted(path for path in candidate_paths if path.is_file())
    artifacts = (
        _create_template_artifact(target, destination_root, template_root, path) for path in template_paths
    )
    return tuple(artifacts)


def _create_template_artifact(
    target: AgentBuildTarget,
    destination_root: Path,
    template_root: Path,
    template_path: Path,
) -> AgentArtifact:
    template_relative_path = template_path.relative_to(template_root)
    relative_path = destination_root / template_relative_path
    content = template_path.read_text(encoding="utf-8")
    return AgentArtifact(target, relative_path, content)


def _artifacts_for_targets(targets: Sequence[AgentBuildTarget]) -> tuple[AgentArtifact, ...]:
    artifact_groups = (create_agent_artifacts(target) for target in targets)
    return tuple(chain.from_iterable(artifact_groups))


def _is_stale(root: Path, artifact: AgentArtifact) -> bool:
    destination = root / artifact.relative_path
    if not destination.is_file():
        return True
    return destination.read_text(encoding="utf-8") != artifact.content


def _build_parser() -> argparse.ArgumentParser:
    parser_description = "Generate ruff-legibility agent artifacts"
    parser = argparse.ArgumentParser(description=parser_description)
    target_help = "package, agents, codex, claude, all, or auto"
    root_help = "repository root for generated files"
    check_help = "report stale generated files without writing"
    parser.add_argument("--target", default=DEFAULT_BUILD_TARGET, help=target_help)
    parser.add_argument("--root", default=REPOSITORY_ROOT, help=root_help)
    parser.add_argument("--check", action="store_true", help=check_help)
    return parser


def _check_command(root: Path, targets: Sequence[AgentBuildTarget]) -> int:
    stale_paths = check_agent_artifacts(root=root, targets=targets)
    for path in stale_paths:
        print(f"out of date {path}", file=sys.stderr)

    if stale_paths:
        return 1

    print("agent artifacts are current")
    return 0


def _write_command(root: Path, targets: Sequence[AgentBuildTarget]) -> int:
    artifacts = write_agent_artifacts(root=root, targets=targets)
    for artifact in artifacts:
        print(f"wrote {artifact.relative_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
